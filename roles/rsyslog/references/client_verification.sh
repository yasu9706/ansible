# TLS設定
## 証明書ファイルの存在・権限確認
ls -l /etc/rsyslog.d/tls/
## ca.pem        644 root:root
## client-cert.pem  644 root:root
## client-key.pem   600 root:root  ← 秘密鍵は600必須

## 証明書の有効期限確認
openssl x509 -in /etc/rsyslog.d/tls/client-cert.pem -noout -dates
## notAfter=Dec 31 00:00:00 2026 GMT  ← 期限切れていないか

## CA証明書でクライアント証明書を検証
openssl verify -CAfile /etc/rsyslog.d/tls/ca.pem /etc/rsyslog.d/tls/client-cert.pem

